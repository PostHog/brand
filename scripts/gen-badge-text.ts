// Outlines the "Built with" line of the website badges (site/agent/badge-render.ts) in
// RoundHog and writes site/src/badge-text.ts. The badge SVGs are shown through <img> on other
// people's sites, where no web font can load, so their lettering ships as a path.
// Run with `node scripts/gen-badge-text.ts` after changing the spec below.

import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { outlineText } from "./lib/outline.ts"

const ROOT = join(import.meta.dirname, "..")
const MODULE = join(ROOT, "site", "src", "badge-text.ts")

/** The badge lettering. The features match the site's `font-variant-ligatures: none`. */
export const BUILT_WITH_SPEC = {
  text: "Built with",
  face: "RoundHog-SemiBold",
  size: 9,
  tracking: 0.02,
  features: ["kern", "-liga", "-clig", "-dlig", "-hlig", "-calt"],
} as const

export function fontFile(face: string): string {
  return join(ROOT, "assets", "fonts", `${face}.woff2`)
}

if (import.meta.main) {
  const { text, face, size, tracking, features } = BUILT_WITH_SPEC
  const outline = await outlineText(readFileSync(fontFile(face)), text, {
    size,
    tracking,
    features,
  })

  writeFileSync(
    MODULE,
    `// Generated by \`node scripts/gen-badge-text.ts\`. Do not edit: change the spec in that script,
// then run it again.

/** A line of RoundHog text as one path: origin at the start of the baseline, y down, px. */
export interface BadgeText {
  text: string
  face: string
  size: number
  /** Extra space between glyphs, in em. */
  tracking: number
  features: readonly string[]
  d: string
  /** Pen position after the last glyph. */
  advance: number
  /** Bounding box of the glyphs' ink. */
  ink: { x: number; y: number; width: number; height: number }
}

export const BUILT_WITH: BadgeText = ${JSON.stringify({ ...BUILT_WITH_SPEC, ...outline })}
`,
  )
  execFileSync("pnpm", ["exec", "oxfmt", "--write", MODULE], { cwd: ROOT, stdio: "inherit" })
  console.log(`Wrote ${MODULE}: advance ${outline.advance}px, ink`, outline.ink)
}
