// Cuts every RoundHog face in assets/fonts/ into the subsets of scripts/lib/fonts.ts,
// writes them to assets/fonts/subsets/, and writes src/fonts/subsets.ts, which declares
// each subset's URL and `unicode-range`.
// Run with `pnpm fonts:subset` after a face in assets/fonts/ changes.

import { execFileSync } from "node:child_process"
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { cutSubsets, toUnicodeRange } from "./lib/fonts.ts"

const ROOT = join(import.meta.dirname, "..")
const FONTS = join(ROOT, "assets", "fonts")
const SUBSETS = join(FONTS, "subsets")
const MODULE = join(ROOT, "src", "fonts", "subsets.ts")

rmSync(SUBSETS, { recursive: true, force: true })
mkdirSync(SUBSETS)

// Faces mostly share each subset's range (upright and italic differ in private-use
// glyphs), so each distinct range is declared once: `latinRange`, or `restRange1`, `restRange2`.
const ranges = new Map<string, string[]>()
const faces: Array<{ face: string; subsets: Array<{ name: string; range: string }> }> = []
for (const file of readdirSync(FONTS).filter((f) => f.endsWith(".woff2"))) {
  const face = file.replace(/\.woff2$/, "")
  const subsets = await cutSubsets(readFileSync(join(FONTS, file)))
  for (const { name, codepoints, woff2 } of subsets) {
    writeFileSync(join(SUBSETS, `${face}-${name}.woff2`), woff2)
    const range = toUnicodeRange(codepoints)
    const seen = ranges.get(name) ?? []
    if (!seen.includes(range)) ranges.set(name, [...seen, range])
  }
  faces.push({
    face,
    subsets: subsets.map((s) => ({ name: s.name, range: toUnicodeRange(s.codepoints) })),
  })
}

const constName = (name: string, range: string): string => {
  const all = ranges.get(name) ?? []
  const base = name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase()) + "Range"
  return all.length > 1 ? `${base}${all.indexOf(range) + 1}` : base
}

writeFileSync(
  MODULE,
  `// Generated by \`pnpm fonts:subset\` (scripts/subset-fonts.ts). Do not edit: change the faces
// in assets/fonts/ or the subsets in scripts/lib/fonts.ts, then run it again.

import type { FontSubset } from "./types.ts"

${[...ranges]
  .flatMap(([name, all]) =>
    all.map((range) => `const ${constName(name, range)}: string = ${JSON.stringify(range)}`),
  )
  .join("\n")}

/** Every RoundHog face's subsets, keyed by the face's file name. Their ranges don't overlap. */
export const roundHogSubsets: Readonly<Record<${faces.map((f) => JSON.stringify(f.face)).join(" | ")}, readonly FontSubset[]>> = {
${faces
  .map(
    ({ face, subsets }) =>
      `${JSON.stringify(face)}: [${subsets
        .map(
          ({ name, range }) =>
            `{ name: ${JSON.stringify(name)}, url: new URL("./subsets/${face}-${name}.woff2", import.meta.url).href, unicodeRange: ${constName(name, range)} }`,
        )
        .join(", ")}],`,
  )
  .join("\n")}
}
`,
)
execFileSync("pnpm", ["exec", "oxfmt", "--write", MODULE], { cwd: ROOT, stdio: "inherit" })
